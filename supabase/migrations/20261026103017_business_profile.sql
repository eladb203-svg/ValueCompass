create table public.business_vocab (
  id        bigint generated by default as identity primary key,
  field     text not null check (field in ('customer_types','revenue_models','regions','competitor_types')),
  code      text not null,
  label_en  text not null,
  label_he  text not null,
  active    boolean not null default true,
  created_at timestamptz not null default now(),
  constraint business_vocab_unique unique (field, code)
);

create table public.term_translations (
  id          bigint generated by default as identity primary key,
  en          text not null,
  he          text not null,
  source      text not null check (source in ('google','model','human')),
  status      text not null default 'unreviewed' check (status in ('unreviewed','approved')),
  reviewed_at timestamptz,
  created_at  timestamptz not null default now(),
  constraint term_translations_unique unique (en)
);

