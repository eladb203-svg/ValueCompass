  fiscal_year       smallint not null check (fiscal_year >= 1900 and fiscal_year <= 2100),
  source_market     text not null default 'US',
  model             text,
  skill_version     text not null,
  -- each field: {"status": ok|other|not_found|failed, "source": xbrl|ai|code, "items": [{..., "source", "quote"|"tag", "status"}], "reasons": [...]}
  core_activity     jsonb not null default '{}'::jsonb,
  segments          jsonb not null default '{}'::jsonb,
  products_services jsonb not null default '{}'::jsonb,
  customer_types    jsonb not null default '{}'::jsonb,
  revenue_models    jsonb not null default '{}'::jsonb,
  regions           jsonb not null default '{}'::jsonb,
  competitors       jsonb not null default '{}'::jsonb,
  competitor_types  jsonb not null default '{}'::jsonb,
  axes_found        jsonb not null default '{}'::jsonb,   -- which XBRL axes the filing had
