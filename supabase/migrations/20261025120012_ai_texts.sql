-- K6c migration 12 - ai_texts: D1 background (English + Hebrew translation) and D2 analysis texts (K6 spec section 6, item 12).
-- A Hebrew background that passed every check is approved at once with human_reviewed = false (the screen shows "תרגום אוטומטי"); a person can confirm, edit or send it back.

create table public.ai_texts (
  id              bigint generated by default as identity primary key,
  company_id      bigint not null references public.companies(id) on delete restrict,
  fiscal_year     smallint not null check (fiscal_year >= 1900 and fiscal_year <= 2100),
  kind            text not null check (kind in ('background','analysis')),
  language        text not null check (language in ('en','he')),
  text            text,
  model           text,
  prompt_version  text not null,
  run_id          bigint references public.score_runs(id) on delete set null,   -- the analysis (D2) belongs to a score run
  run_label       text not null default '',
  accession       text,
  state           text not null default 'stored',
  approval_status text not null check (approval_status in ('approved','pending_review','failed')),
  edited_by       text not null default 'ai' check (edited_by in ('ai','human')),
  human_reviewed  boolean not null default false,
  checks          jsonb not null default '{}'::jsonb,
  quotes          jsonb not null default '[]'::jsonb,
  details         jsonb not null default '{}'::jsonb,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  constraint ai_texts_unique unique (company_id, fiscal_year, kind, language, prompt_version, run_label),
  constraint ai_texts_text_check check (approval_status = 'failed' or text is not null)
);

alter table public.ai_texts enable row level security;
create policy ai_texts_select_authenticated on public.ai_texts for select to authenticated using (approval_status = 'approved');
revoke all on public.ai_texts from anon;
grant select on public.ai_texts to authenticated;
grant all on public.ai_texts to service_role;
