-- K6d-2 fixes (2026-11-01) - data_gap_review: the review list of criteria that stay Missing after a score although the company is not exempt from them. Administrator only (service role);
-- no access for anon or authenticated, like every other table of the access model. One row per company and criterion; a row that closed more than 180 days ago goes in the weekly cleanup.

create table public.data_gap_review (
  id               bigint generated by default as identity primary key,
  company_id       bigint not null references public.companies(id) on delete cascade,
  item_key         text not null,                       -- the criterion: 'B 3.7.3' (Buffett) / 'G 3.2.2' (Graham)
  fiscal_year      smallint check (fiscal_year is null or (fiscal_year >= 1900 and fiscal_year <= 2100)),
  accession        text,                                -- the annual report the passage comes from
  reason           text not null,                       -- the note the engine wrote for the missing item
  closest_passage  text,                                -- the closest passage of the report by the keywords of the item, about 300 characters; no model call
  family           text not null,                       -- the group of items with the same kind of gap
  state            text not null default 'open' check (state in ('open','fixed','genuine')),
  first_seen       timestamptz not null default now(),
  last_seen        timestamptz not null default now(),
  closed_at        timestamptz,                         -- set when the state becomes fixed or genuine
  unique (company_id, item_key)
);

create index data_gap_review_family on public.data_gap_review (family, state);

alter table public.data_gap_review enable row level security;
revoke all on public.data_gap_review from anon, authenticated;
grant all on public.data_gap_review to service_role;

comment on table public.data_gap_review is 'Criteria still Missing after the score, with the reason and the closest passage of the annual report. Administrator only. Closed rows (fixed / genuine) older than 180 days are deleted by the weekly cleanup.';
