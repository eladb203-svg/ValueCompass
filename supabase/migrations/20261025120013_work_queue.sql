-- K6c migration 13 - work_queue: one queue for data jobs and AI tasks (K6 spec section 6, item 13). Only the runner (service role) reads and writes it;
-- the screen writes requests through a function (K7).

create table public.work_queue (
  id           bigint generated by default as identity primary key,
  company_id   bigint references public.companies(id) on delete cascade,
  job_type     text not null check (job_type in ('initial_import','backfill','new_report','amendment','repair','score','ai_classify','ai_extract','ai_assess','ai_background','analysis')),
  fiscal_year  smallint check (fiscal_year is null or (fiscal_year >= 1900 and fiscal_year <= 2100)),
  skill        text,
  priority     smallint not null default 3 check (priority between 1 and 3),   -- 1 a user asked, 2 new annual report, 3 backfill
  state        text not null default 'queued' check (state in ('queued','running','done','failed','deferred_quota')),
  attempts     integer not null default 0 check (attempts >= 0),
  next_run_at  timestamptz not null default now(),
  last_error   text,
  payload      jsonb not null default '{}'::jsonb,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

-- the same open task is queued once
create unique index work_queue_open_unique on public.work_queue (company_id, job_type, coalesce(fiscal_year, 0), coalesce(skill, ''))
  where state in ('queued','running','deferred_quota');
create index work_queue_pick on public.work_queue (priority, next_run_at) where state in ('queued','deferred_quota');

alter table public.work_queue enable row level security;
revoke all on public.work_queue from anon, authenticated;
grant all on public.work_queue to service_role;
